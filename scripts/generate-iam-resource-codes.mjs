import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readResourceRegistries } from './lib/resource-registries.mjs'
import { format } from 'prettier'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pages = readResourceRegistries(root)
const page = (key) => {
  const value = pages.find(
    (p) => p.registry_file.includes('/permission-governance/') && p.registry_key === key,
  )
  if (!value) throw new Error(`Missing permission governance registry: ${key}`)
  return value
}
const result = {
  systemResources: {
    view: page('catalog').resource_code,
    create: page('catalog').buttons.create.resource_code,
    update: page('catalog').buttons.edit.resource_code,
  },
  permissions: {
    view: page('permissions').resource_code,
    create: page('permissions').buttons.create.resource_code,
    copy: page('permissions').buttons.copy.resource_code,
    update: page('permissions').buttons.edit.resource_code,
    configure: page('configuration').resource_code,
    saveConfiguration: page('configuration').buttons.save.resource_code,
  },
  roles: {
    authorization: page('roleAuthorization').resource_code,
    saveAuthorization: page('roleAuthorization').buttons.save.resource_code,
  },
  members: { effectivePermissions: page('userEffective').resource_code },
}
const source = await format(
  '// Generated by pnpm iam:codes:generate. Identity owner: permission-governance/iam-resource.registry.ts.\n' +
    `export const IAM_PERMISSION_GOVERNANCE_RESOURCES = Object.freeze(${JSON.stringify(result, null, 2)} as const)\n`,
  { parser: 'typescript', semi: false, singleQuote: true, printWidth: 100 },
)
const path = join(root, 'src/shared/constants/iamPermissionGovernanceResources.generated.ts')
if (process.argv.includes('--check')) {
  if (!existsSync(path) || readFileSync(path, 'utf8') !== source)
    throw new Error('Stale IAM resource code projection; run pnpm iam:codes:generate')
} else writeFileSync(path, source)
console.log('IAM resource code projection checked')
